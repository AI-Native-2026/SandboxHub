let currentLang: Lang = (typeof localStorage !== "undefined" && (localStorage.getItem("sh-lang") as Lang)) || "zh";

export function tr(cn: string): string {
  if (currentLang === "zh") return cn;
  return CN_EN[cn] ?? cn;
}

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: string) => string;
}

const Ctx = createContext<I18nCtx>({ lang: "zh", setLang: () => {}, t: (k) => k });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => (localStorage.getItem("sh-lang") as Lang) || "zh");
  useEffect(() => {
    currentLang = lang;
    localStorage.setItem("sh-lang", lang);
    document.documentElement.setAttribute("lang", lang === "zh" ? "zh-CN" : "en");
  }, [lang]);
  currentLang = lang;
  const t = (k: string) => DICT[lang][k] ?? DICT.zh[k] ?? k;
  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
